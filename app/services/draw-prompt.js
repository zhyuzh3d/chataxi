(function (app) {
  "use strict";
  // 绘图动作的提示词片段。只在**确实配置了可用绘图卡片**时注入（见 llm.js 的 complete），
  // 否则角色会写出一个永远不被执行的动作块。
  //
  // 约束来自业主的明确要求：
  //   1. 动作块只写在正文之后，且对用户不可见；
  //   2. 每轮最多一个动作块、最多一张图；
  //   3. 参考图不是模型决定的 —— 模型只回答"这张图画不画我自己"，
  //      定妆照由动作执行层顶上去。所以这里只要求 selfPortrait 是个布尔判断，
  //      不许它去描述"用某张图当参考"。
  //   4. 用户索要照片时，由角色结合上下文自己决定画不画；图生成后自动发到对话里，
  //      所以正文里不许写"已经画好了"这种完成时（业主 2026-09-26）。
  //   5. **判定必须是二值的：不要画面 / 要给画面。给画面就只有动作块这一条路**
  //      （业主 2026-09-27：「决不能用文字描述替代照片，如果要响应用户的要求，就应该调用
  //      生图工具来实现生图」）。所以下面把"文字伪交付"的几种写法**逐条点名禁掉** ——
  //      这几种写法是模型自己的历史里学来的，光说"要画图"挡不住（见 llm.js 的 drawNote）。
  //   6. **prompt 的写法也要教**（业主 2026-09-27：「你来规划如何引导她撰写简明扼要但又高效
  //      的提示词」）：给一套四段骨架 + 密度优先的判据，而不是只给一个字数区间。
  //
  // 标点按业主的规范（2026-09-23）统一用半角逗号。
  //
  // 用定妆照当参考图时，钉在**图像**提示词开头的那一句（业主 2026-09-26 指定）：
  // 参考图只提供身份，头姿必须与参考图不同，身体姿势与构图完全按描述来。
  // 不加这句，模型会把参考图当构图模板照抄，"定妆照"就退化成"同一张图再画一遍"。
  // 放在这个模块里，是因为它和 instruction() 一样是给模型看的话，而不是界面文案 ——
  // check-i18n 的 PROMPT_FILES 正好把这类文本排除在门禁外（它不该有英文对照）。
  var REFERENCE_PREFIX = "参考图1仅仅作为角色身份, 头部姿势必须图1不同, 身体姿势和构图必须按下面描述。";

  function instruction(hasPortrait) {
    var portrait = hasPortrait
      ? "你有一张定妆照：selfPortrait 写 true 时系统会把定妆照作为参考图交出去, 画面会更接近你原本的样子 —— 所以画你自己的时候**必须写 true**, 写成 false 就等于把定妆照丢掉了。即便如此, prompt 里仍然要写清容貌、发型、穿着与画面, 不要只写「自拍」。"
      : "你目前没有定妆照, selfPortrait 写 true 只会当作普通绘图处理。因此当你画自己时, prompt 里必须自己写清容貌、发型、穿着与画面。";
    return "你没有相机, 也没有一张现成的、可以直接发出去的「照片」—— 用户想看的你的样子, 你能给的只有画出来的那一张。所以「发照片」和「画图」是同一件事, 不是两件：不要回答「我发不了照片」「照片不能生成」这类话, 那样的回答是错的。\n\n" +
      "**每一轮只有两个选项, 没有第三个：**\n" +
      "A. 这一轮不需要画面 ⇒ 正常回话, 不写动作块。\n" +
      "B. 这一轮要给画面 ⇒ **必须写动作块**。只要你的答复里带着「我给你一张图 / 这是照片 / 见图」这层意思, 动作块就必须在。\n" +
      "**没有 C。** 把画面用文字描写一遍、写一句「发送了一个图片：…」、附上图片地址或文件编号来充当照片 —— 这些全部算错：用户那边只会看到一段字, 什么图都没有, 你要表达的东西一分也没送到。\n\n" +
      "下面这些话说的都是 B 这种「要一张图」, 一律按同样方式处理, 不要因为它们用词不同就区别对待：「发张照片」「发张图」「给我发一张」「拍张照」「画一张」「来张自拍 / 写真 / 特写 / 全身照」「给我看看你的样子」「你长什么样」「配张图」。凡是这样要图的场合 —— 不管他用的是「照片」还是「画」这个词 —— 你都要按下面的格式给出绘图动作块, 只回一段文字是不行的。当然, 画不画仍由你结合上下文决定：不想画就正常回话, 不写动作块。要画的时候, 在正文之后另起一段, 附上一个绘图动作块, 格式严格如下：\n" +
      "<<<chataxi-action\n" +
      "{\"type\":\"draw\",\"prompt\":\"画面提示词\",\"selfPortrait\":false}\n" +
      ">>>\n\n" +
      "规则：\n" +
      "1. 动作块必须写在正文之后, 块内只放这一段 JSON, 不要加 Markdown 围栏、注释或说明文字。\n" +
      "2. 每轮最多写一个动作块, 也就是说每轮最多画一张图。不需要配图时就不要写动作块, 不要每轮都画。\n" +
      "3. 想配图又想说话, 就正常写正文再加动作块；只想给图不想说话, 可以完全不写正文, 只输出动作块。\n" +
      "4. 动作块对用户不可见：不要在正文里提到它, 不要解释你在调用工具, 也不要复述它的内容。\n" +
      "5. **正文里绝对不许出现这些写法**：「发送了一个图片：…」「图片地址是：…」、任何 `/hermit/…` 路径或附件编号、`(图片)`、`[图片]`、`见下图`、`图片已生成`、`我已经发给你了`。历史里带方括号的那几行（形如 `[系统附注] …`）是**系统写给模型的备注, 不是你自己说过的话**, 更不是你该照搬的句式 —— 看到它也不许学着那样说。要给图, 唯一的做法就是写动作块。\n" +
      "6. prompt 写 40 到 120 字, 但**信息密度比长度重要**：宁可 60 个字全是具体名词, 也不要 120 个字都是漂亮的空话。按四段凑齐：**谁在做什么**（具体到容貌、发型、穿着、表情、动作）→ **在哪、周围有什么** → **光与色调** → **画风**（一个短语）。\n" +
      "7. 写 prompt 的几条硬要求：具体名词压过抽象形容词（写「白色吊带连衣裙」, 不要写「很好看的衣服」）；一个主体一个动作, 别把两个场景塞进同一张图；**不写否定句**（要「短发」, 不要「不要长发」）；不要要求画面里出现文字、水印或对话框；同一个角色的容貌与穿着始终用**同一套词**, 否则每张图看起来会像换了一个人。\n" +
      "8. selfPortrait 是「这张图是不是画你自己」的开关, 只有 true 才会把角色的定妆照带进去：用户要你的照片、你自己展示容貌与形象（自拍、写真、特写、全身照、表情或动作展示）时, **必须写 true**；画风景、物品、他人或抽象画面时才写 false。写反了, 画面里就不是你自己的长相了。\n" +
      "9. 你要的这张图会在你这条回复之后自动出现在对话里, 用户立刻就能看到：正文里自然表达就好, 不要解释生成过程, 也不要写「我已经画好了」这类完成时 —— 你写字的时候图还没画出来。\n" +
      portrait;
  }

  app.services = app.services || {};
  app.services.drawPrompt = { instruction: instruction, referencePrefix: REFERENCE_PREFIX };
})(window.chataxi);
